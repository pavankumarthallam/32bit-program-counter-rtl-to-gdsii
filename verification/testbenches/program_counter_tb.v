`timescale 1ns / 1ps

module program_counter_tb;

    //------------------------------------------------------------------
    // Parameters
    //------------------------------------------------------------------
    parameter XLEN = 32;
    parameter RESET_VECTOR = 32'h0000_0000;

    //------------------------------------------------------------------
    // Testbench Signals
    //------------------------------------------------------------------
    reg clk;
    reg reset;
    reg enable;
    reg stall;
    reg branch_taken;
    reg jump_taken;

    reg [XLEN-1:0] branch_target;
    reg [XLEN-1:0] jump_target;

    wire [XLEN-1:0] pc;

    //------------------------------------------------------------------
    // DUT
    //------------------------------------------------------------------

    program_counter_top DUT
    (
        .clk(clk),
        .reset(reset),
        .enable(enable),
        .stall(stall),
        .branch_taken(branch_taken),
        .jump_taken(jump_taken),
        .branch_target(branch_target),
        .jump_target(jump_target),
        .pc(pc)
    );

    //------------------------------------------------------------------
    // Clock Generation (10 ns period)
    //------------------------------------------------------------------

    initial
    begin
        clk = 0;
        forever #5 clk = ~clk;
    end

    //------------------------------------------------------------------
    // Task : Check PC
    //------------------------------------------------------------------

    task check_pc;
        input [31:0] expected;

        begin
            #1;
            if(pc !== expected)
            begin
                $display("--------------------------------------------------");
                $display("ERROR at time %0t", $time);
                $display("Expected PC = %h", expected);
                $display("Actual   PC = %h", pc);
                $display("--------------------------------------------------");
                $stop;
            end
            else
            begin
                $display("[%0t] PASS : PC = %h", $time, pc);
            end
        end
    endtask

    //------------------------------------------------------------------
    // Test Sequence
    //------------------------------------------------------------------

    initial
    begin

        //--------------------------------------------------------------
        // Initialize
        //--------------------------------------------------------------

        reset          = 1;
        enable         = 1;

        stall          = 0;
        branch_taken   = 0;
        jump_taken     = 0;

        branch_target  = 32'h00000040;
        jump_target    = 32'h00000100;

        //--------------------------------------------------------------
        // Apply Reset
        //--------------------------------------------------------------

        @(posedge clk);
        check_pc(RESET_VECTOR);

        //--------------------------------------------------------------
        // Release Reset
        //--------------------------------------------------------------

        reset = 0;

        //--------------------------------------------------------------
        // Sequential Execution
        //--------------------------------------------------------------

        @(posedge clk);
        check_pc(32'h00000004);

        @(posedge clk);
        check_pc(32'h00000008);

        @(posedge clk);
        check_pc(32'h0000000C);

        //--------------------------------------------------------------
        // Stall
        //--------------------------------------------------------------

        stall = 1;

        @(posedge clk);
        check_pc(32'h0000000C);

        @(posedge clk);
        check_pc(32'h0000000C);

        stall = 0;

        //--------------------------------------------------------------
        // Continue
        //--------------------------------------------------------------

        @(posedge clk);
        check_pc(32'h00000010);

        //--------------------------------------------------------------
        // Branch
        //--------------------------------------------------------------

        branch_taken = 1;
        branch_target = 32'h00000080;

        @(posedge clk);
        check_pc(32'h00000080);

        branch_taken = 0;

        //--------------------------------------------------------------
        // Sequential after Branch
        //--------------------------------------------------------------

        @(posedge clk);
        check_pc(32'h00000084);

        //--------------------------------------------------------------
        // Jump
        //--------------------------------------------------------------

        jump_taken = 1;
        jump_target = 32'h00000200;

        @(posedge clk);
        check_pc(32'h00000200);

        jump_taken = 0;

        //--------------------------------------------------------------
        // Sequential after Jump
        //--------------------------------------------------------------

        @(posedge clk);
        check_pc(32'h00000204);

        //--------------------------------------------------------------
        // Enable = 0
        //--------------------------------------------------------------

        enable = 0;

        @(posedge clk);
        check_pc(32'h00000204);

        @(posedge clk);
        check_pc(32'h00000204);

        enable = 1;

        //--------------------------------------------------------------
        // Continue
        //--------------------------------------------------------------

        @(posedge clk);
        check_pc(32'h00000208);

        //--------------------------------------------------------------
        // Priority Test
        // Jump should have priority over Branch
        //--------------------------------------------------------------

        branch_taken  = 1;
        jump_taken    = 1;

        branch_target = 32'h00000300;
        jump_target   = 32'h00000400;

        @(posedge clk);
        check_pc(32'h00000400);

        branch_taken = 0;
        jump_taken   = 0;

        //--------------------------------------------------------------
        // Finish
        //--------------------------------------------------------------

        @(posedge clk);

        $display("");
        $display("==============================================");
        $display(" ALL TEST CASES PASSED SUCCESSFULLY ");
        $display("==============================================");
        $finish;

    end

endmodule